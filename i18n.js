// Plain-language messages for the errors people actually hit (the original text is kept for anything unknown).
function friendly(e) {
  const m = String((e && e.message) || e || ''), c = String((e && (e.code || e.error_code)) || ''), has = re => re.test(m) || re.test(c);
  if (has(/too many attempts/i)) return t('Too many wrong passwords for this username. Wait 15 minutes, or log in with your email.');
  if (has(/rate.?limit|over_email_send/i)) return t('Too many emails were sent just now. Please wait about an hour and try again, or ask an admin to set a new password for you.');
  if (has(/invalid.?login|invalid_credentials/i)) return t('Wrong username/email or password.');
  if (has(/not.?confirmed/i)) return t('Please confirm your email first: open the link we sent you (check the spam folder too).');
  if (has(/already.?(registered|exists)/i)) return t('This email already has an account. Log in instead, or use "Forgot password?".');
  if (has(/failed to fetch|networkerror|load failed|network request failed/i)) return t('No connection. Check your internet and try again.');
  if (has(/answers are closed/i)) return t('Answers are closed. Ask an admin.');
  if (has(/play window/i)) return t('A day can only be started during the play window. Ask an admin.');
  if (has(/admins only|row-level security|permission denied/i)) return t("You don't have permission to do that. Ask an admin.");
  if (has(/change this name/i)) return t('Only an admin or the player can change this name.');
  if (has(/own avatar/i)) return t('Only the player can change their own photo.');
  if (has(/your own account/i)) return t('You cannot remove your own account.');
  if (has(/jwt expired|refresh.?token|session.?(expired|not found)/i)) return t('Your session has expired. Please log in again.');
  if (has(/at least 6|weak_password|should be at least/i)) return t('The password needs at least 6 characters.');
  if (has(/schema cache|could not find the (function|table)|does not exist/i)) return t('The database needs an update. Tell an admin.');
  if (has(/unknown time zone/i)) return t('Unknown time zone.');
  return m || t('Something went wrong. Please try again.');
}

